def build_ledger(matrix: pd.DataFrame, games: pd.DataFrame,
                 market_ref: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    """Produce the immutable OOF ledger + fold metadata."""
    prod_model, _, prod_meta = load_shadow()
    if prod_model is None:
        raise RuntimeError("frozen shadow artifact could not be loaded")

    ref = market_ref.set_index("game_id")
    gmeta = games.set_index(games["game_id"].astype(str))
    market_col = {"moneyline": "market_moneyline", "spread": "market_spread", "total": "market_total"}
    shadow_col = wr.MARKET_SHADOW_COL

    records = []
    fold_meta = []

    def emit(frame, preds, population, fold_label, train_cut, calib_season, fold_hash):
        masks = _outcome_masks(frame)
        for pos, (_, row) in enumerate(frame.iterrows()):
            gid = str(row["game_id"])
            snap = _feature_snapshot_hash(row)
            imp_names = [c for c in FROZEN_FEATURES if pd.isna(row[c])]
            for market in MARKETS:
                m = masks[market]
                excluded = bool(m["excluded"][pos])
                mref = ref.loc[gid] if gid in ref.index else None
                mprob = float(mref[market_col[market]]) if mref is not None else np.nan
                match_status = "MATCHED" if np.isfinite(mprob) else "NO_QUOTE"
                cp = np.nan
                if market == "spread":
                    cp = float(row["home_spread"])
                elif market == "total":
                    cp = float(row["total_line"])
                records.append({
                    "game_id": gid, "season": int(row["season"]), "week": int(row["week"]),
                    "kickoff_utc": str(gmeta.loc[gid, "scheduled_kickoff_utc"]) if gid in gmeta.index else "",
                    "evaluation_population": population, "evaluation_fold": fold_label,
                    "as_of_utc": str(gmeta.loc[gid, "scheduled_kickoff_utc"]) if gid in gmeta.index else "",
                    "home_team": str(row["home_team_id"]), "away_team": str(row["away_team_id"]),
                    "market": market, "contract_point": cp,
                    "home_spread": float(row["home_spread"]), "total_line": float(row["total_line"]),
                    "shadow_probability": float(preds.loc[frame.index[pos], shadow_col[market]]),
                    "market_probability": mprob, "production_probability": mprob,
                    "production_source": "MARKET_BASELINE",
                    "realized_outcome": (m["label"] if excluded else int(m["y"][pos])),
                    "push_or_tie": excluded, "feature_snapshot_hash": snap,
                    "fold_model_hash": fold_hash, "production_artifact_hash": PRODUCTION_ARTIFACT_HASH,
                    "training_cutoff": train_cut, "calibration_season": calib_season,
                    "imputed_feature_count": len(imp_names),
                    "imputed_feature_names": ";".join(imp_names),
                    "historical_availability_assumption": "HISTORICAL_AVAILABILITY_ASSUMPTION",
                    "market_quote_horizon": "SCHEDULE_REFERENCE",
                    "market_contract_match_status": match_status,
                })

    # --- Population A: locked 2025 Week 1 holdout via the production artifact ---
    holdout = matrix[(matrix["season"] == 2025) & (matrix["week"] == 1)].copy()
    holdout_pred = _predict(prod_model, holdout)
    holdout_hash = _fold_model_hash(["PRODUCTION_ARTIFACT"], prod_model, holdout_pred)
    emit(holdout, holdout_pred, "A_locked_2025_holdout", "locked_2025",
         prod_meta["training_cutoff_season"], prod_meta["calibration_season"], holdout_hash)

    # --- Populations B/C/D: rolling-origin OOF folds ---
    for fold in wr.FOLDS:
        ts = fold["test_season"]
        train, calib, test = wr.build_fold_frames(matrix, fold)
        model = JointScoreModel(numeric_features=FROZEN_FEATURES)
        model.fit(train, calibration=calib)
        preds = _predict(model, test)
        fold_hash = _fold_model_hash(train["game_id"].tolist(), model, preds)
        # training medians for imputed features (leakage diagnostic)
        train_medians = {c: float(np.nanmedian(train[c].to_numpy(float))) for c in FROZEN_FEATURES}
        fold_meta.append({
            "test_season": ts, "train_max_season": fold["train_max_season"],
            "calibration_season": fold["calibration_season"],
            "n_train": int(len(train)), "n_calibration": int(len(calib)),
            "n_test_total": int(len(test)),
            "n_week1": int((test["week"] == 1).sum()),
            "fold_model_hash": fold_hash, "train_medians": train_medians,
        })
        for population, wk_mask in (
            ("B_week1_oof", test["week"] == 1),
            ("C_weeks1_2_oof", test["week"].isin([1, 2])),
            ("D_weeks3plus_oof", test["week"] >= 3),
        ):
            sub = test[wk_mask]
            emit(sub, preds.loc[sub.index], population, f"test_{ts}",
                 fold["train_max_season"], fold["calibration_season"], fold_hash)

    ledger = pd.DataFrame.from_records(records)[LEDGER_COLUMNS]
    return ledger, {"folds": fold_meta, "artifact": prod_meta}


