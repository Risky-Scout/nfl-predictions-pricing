# ---------------------------------------------------------------------------
def _feature_snapshot_hash(row: pd.Series) -> str:
    payload = {
        "game_id": str(row["game_id"]),
        "columns": FROZEN_FEATURES,
        "values": [None if pd.isna(row[c]) else round(float(row[c]), 10) for c in FROZEN_FEATURES],
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()


def _outcome_masks(frame: pd.DataFrame) -> dict:
    """Graded/push/tie masks and binary outcomes per market (exact contract)."""
    margin = frame["home_margin"].to_numpy(float)
    total_pts = frame["total_points"].to_numpy(float)
    spread = frame["home_spread"].to_numpy(float)
    total_line = frame["total_line"].to_numpy(float)

    tie = margin == 0.0
    ml_y = (margin > 0).astype(float)

    spread_int = np.isfinite(spread) & np.isclose(spread, np.round(spread))
    ats_push = spread_int & np.isclose(margin + spread, 0.0)
    ats_y = (margin + spread > 0).astype(float)

    total_int = np.isfinite(total_line) & np.isclose(total_line, np.round(total_line))
    tot_push = total_int & np.isclose(total_pts, total_line)
    tot_y = (total_pts > total_line).astype(float)

    return {
        "moneyline": {"graded": ~tie, "excluded": tie, "y": ml_y, "label": "TIE"},
        "spread": {"graded": ~ats_push, "excluded": ats_push, "y": ats_y, "label": "PUSH"},
        "total": {"graded": ~tot_push, "excluded": tot_push, "y": tot_y, "label": "PUSH"},
    }


def _fold_model_hash(train_ids, model, test_pred: pd.DataFrame) -> str:
    def _cal(c):
        m = c.model
        return None if m is None else [round(float(m.intercept_[0]), 10), round(float(m.coef_[0][0]), 10)]
    payload = {
        "train_game_ids": sorted(str(x) for x in train_ids),
        "margin_sd": round(float(model.margin_sd_), 10),
        "total_sd": round(float(model.total_sd_), 10),
        "rho": round(float(model.residual_correlation_), 10),
        "ml_cal": _cal(model.ml_calibrator),
        "ats_cal": _cal(model.ats_calibrator),
        "ou_cal": _cal(model.ou_calibrator),
        "test_pred": [[round(float(v), 10) for v in test_pred[c]]
                      for c in ("home_win_probability_no_tie",
                                "home_cover_probability_no_push",
                                "over_probability_no_push")],
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()


def _predict(model, frame: pd.DataFrame) -> pd.DataFrame:
    pred = model.predict_markets(frame)
    return pd.DataFrame({
        "game_id": frame["game_id"].astype(str).to_numpy(),
        "home_win_probability_no_tie": pred["home_win_probability_no_tie"].to_numpy(),
        "home_cover_probability_no_push": pred["home_cover_probability_no_push"].to_numpy(),
        "over_probability_no_push": pred["over_probability_no_push"].to_numpy(),
    }, index=frame.index)


