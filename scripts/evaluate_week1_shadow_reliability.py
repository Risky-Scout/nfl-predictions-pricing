def _slice(ledger, population, market):
    return ledger[(ledger["evaluation_population"] == population) & (ledger["market"] == market)].copy()


def _graded(sub):
    return sub[~sub["push_or_tie"].astype(bool)].copy()


def score_population(ledger, population, market):
    sub = _graded(_slice(ledger, population, market))
    paired = sub[np.isfinite(sub["shadow_probability"]) & np.isfinite(sub["market_probability"])].copy()
    y = paired["realized_outcome"].astype(float).to_numpy()
    ps = paired["shadow_probability"].to_numpy(float)
    pm = paired["market_probability"].to_numpy(float)
    seasons = paired["season"].to_numpy()
    shadow_metrics = wr.score_market(y, ps)
    market_metrics = wr.score_market(y, pm)
    boot = wr.paired_bootstrap_logloss_diff(y, ps, pm, seasons)
    all_sub = _slice(ledger, population, market)
    return {
        "population": population, "market": market,
        "n_graded": int(len(sub)), "n_paired": int(len(paired)),
        "n_total_rows": int(len(all_sub)),
        "n_excluded_push_or_tie": int(all_sub["push_or_tie"].astype(bool).sum()),
        "observed_push_or_tie_rate": (float(all_sub["push_or_tie"].astype(bool).mean())
                                      if len(all_sub) else wr.NOT_ESTIMABLE),
        "paired_market_coverage": (float(len(paired) / len(sub)) if len(sub) else wr.NOT_ESTIMABLE),
        "shadow": shadow_metrics, "market": market_metrics, "comparison": boot,
    }


def loso_logloss_sign(ledger, market):
    """Leave-one-season-out pooled shadow-market log-loss diff for population B."""
    sub = _graded(_slice(ledger, "B_week1_oof", market))
    paired = sub[np.isfinite(sub["shadow_probability"]) & np.isfinite(sub["market_probability"])]
    seasons = sorted(paired["season"].unique().tolist())
    full = wr.binary_log_loss(paired["realized_outcome"].astype(float), paired["shadow_probability"]) \
        - wr.binary_log_loss(paired["realized_outcome"].astype(float), paired["market_probability"])
    out = {"full_diff": float(full), "per_removed": {}}
    signs = set()
    for s in seasons:
        red = paired[paired["season"] != s]
        d = wr.binary_log_loss(red["realized_outcome"].astype(float), red["shadow_probability"]) \
            - wr.binary_log_loss(red["realized_outcome"].astype(float), red["market_probability"])
        out["per_removed"][str(s)] = float(d)
        signs.add(np.sign(round(d, 12)))
    out["sign_stable"] = len(signs) <= 1
    return out


def imputation_diagnostics(ledger, fold_meta):
    b1 = _slice(ledger, "B_week1_oof", "moneyline").drop_duplicates("game_id")
    d3 = _slice(ledger, "D_weeks3plus_oof", "moneyline").drop_duplicates("game_id")

    def counts(df):
        return {
            "n_games": int(len(df)),
            "mean_imputed_feature_count": (float(df["imputed_feature_count"].mean()) if len(df) else wr.NOT_ESTIMABLE),
            "imputed_feature_names": sorted({n for names in df["imputed_feature_names"] for n in (names.split(";") if names else [])}),
        }

    # per-feature missing % in Week 1 OOF
    per_feature = {}
    for c in FROZEN_FEATURES:
        miss = b1["imputed_feature_names"].apply(lambda s: c in (s.split(";") if s else []))
        per_feature[c] = float(miss.mean()) if len(b1) else 0.0

    # fold training medians for imputed features + their percentile in the training distribution (== 0.5 for median)
    fold_medians = {}
    for fm in fold_meta["folds"]:
        wk1_imputed = sorted({n for names in
                              _slice(ledger, "B_week1_oof", "moneyline")
                              [_slice(ledger, "B_week1_oof", "moneyline")["evaluation_fold"] == f"test_{fm['test_season']}"]
                              ["imputed_feature_names"] for n in (names.split(";") if names else [])})
        fold_medians[str(fm["test_season"])] = {
            "imputed_features": wk1_imputed,
            "training_median": {c: round(fm["train_medians"][c], 8) for c in wk1_imputed},
            "training_median_percentile": {c: 0.5 for c in wk1_imputed},
        }

    return {
        "week1": counts(b1), "weeks3plus": counts(d3),
        "week1_per_feature_missing_fraction": per_feature,
        "fold_training_medians_for_imputed": fold_medians,
    }


def _dispersion(ledger, population, market):
    sub = _graded(_slice(ledger, population, market))
    p = sub[np.isfinite(sub["shadow_probability"])]["shadow_probability"].to_numpy(float)
    return float(p.std(ddof=0)) if len(p) else wr.NOT_ESTIMABLE


