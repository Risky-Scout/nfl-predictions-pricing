def _fmt(v, nd=4):
    if isinstance(v, str):
        return v
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "NOT_ESTIMABLE"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def _ci(ci):
    if not ci or ci[0] == wr.NOT_ESTIMABLE:
        return "NOT_ESTIMABLE"
    return f"[{ci[0]:+.4f}, {ci[1]:+.4f}]"


