def report_json_body(report: dict) -> str:
    return json.dumps(report, indent=2, sort_keys=True, default=str) + "\n"


def write_outputs(report: dict, ledger: pd.DataFrame) -> dict:
    LEDGER_CSV.parent.mkdir(parents=True, exist_ok=True)
    ledger_sorted = ledger.sort_values(
        ["evaluation_population", "evaluation_fold", "game_id", "market"], kind="stable").reset_index(drop=True)
    ledger_sorted.to_csv(LEDGER_CSV, index=False, float_format="%.10g", lineterminator="\n")
    LEDGER_SCHEMA.write_text(json.dumps(
        {"schema": LEDGER_COLUMNS, "row_count": report["ledger"]["row_count"],
         "sha256": report["ledger"]["sha256"]}, indent=2) + "\n")

    md = render_markdown(report)
    md_hash = hashlib.sha256(md.encode()).hexdigest()
    REPORT_MD.write_text(md)

    body = report_json_body(report)
    report_hash = hashlib.sha256(body.encode()).hexdigest()
    REPORT_JSON.parent.mkdir(parents=True, exist_ok=True)
    REPORT_JSON.write_text(body)
    return {"ledger_hash": report["ledger"]["sha256"], "report_json_sha256": report_hash,
            "report_md_sha256": md_hash}


def main() -> dict:
    games = pd.read_parquet(GAMES_PATH)
    pbp = pd.read_parquet(PBP_PATH)
    matrix, manifest = build_augmented_feature_matrix(games, pbp)
    if manifest["all_features"] != FROZEN_FEATURES:
        raise ValueError("training features drifted from FROZEN_FEATURES")
    market_ref = wr.schedule_reference_market(games)

    report, ledger = run_evaluation(matrix, games, market_ref)
    hashes = write_outputs(report, ledger)
    print(json.dumps({
        **hashes,
        "reliability_status": report["reliability_status"],
        "recommendation": report["production"]["recommendation"],
        "week1_oof_games": report["samples_and_coverage"]["B_week1_oof"]["n_games"],
        "determinism": report["determinism"]["ledger_reproducible"],
    }, indent=2))
    return report


