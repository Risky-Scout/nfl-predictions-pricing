def determinism_check(matrix, games, market_ref):
    l1, _ = build_ledger(matrix, games, market_ref)
    l2, _ = build_ledger(matrix, games, market_ref)
    h1 = wr.deterministic_frame_hash(l1, LEDGER_COLUMNS)
    h2 = wr.deterministic_frame_hash(l2, LEDGER_COLUMNS)
    return h1 == h2, h1


