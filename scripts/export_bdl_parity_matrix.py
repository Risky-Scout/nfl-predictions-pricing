"""Export the BDL historical/live parity matrix (Fix 5, Section 18) as JSON.

Run: PYTHONPATH=src python scripts/export_bdl_parity_matrix.py

Writes docs/BDL_PARITY_MATRIX.json (machine-readable) and
docs/BDL_PARITY_MATRIX.md (human-readable). Purely a serialization of
nfl_hybrid.providers.balldontlie.parity.PARITY_MATRIX -- no network access,
no data dependency.
"""
from __future__ import annotations

import json
from pathlib import Path

from nfl_hybrid.providers.balldontlie.parity import PARITY_MATRIX, as_records

REPO_ROOT = Path(__file__).resolve().parents[1]
JSON_OUTPUT_PATH = REPO_ROOT / "docs" / "BDL_PARITY_MATRIX.json"
MD_OUTPUT_PATH = REPO_ROOT / "docs" / "BDL_PARITY_MATRIX.md"


def _render_markdown() -> str:
    eligible = sum(1 for e in PARITY_MATRIX if e.production_eligible)
    lines = [
        "# BDL Historical/Live Parity Matrix",
        "",
        "Generated by `scripts/export_bdl_parity_matrix.py` from "
        "`nfl_hybrid.providers.balldontlie.parity.PARITY_MATRIX` -- do not hand-edit; "
        "edit the Python source and regenerate. See `docs/BDL_LIVE_INTEGRATION.md` for "
        "the full provider contract this matrix supports.",
        "",
        f"**{eligible} of {len(PARITY_MATRIX)} feature families are production-eligible** "
        "(`EXACT` or `VALIDATED_TRANSFORM`). No `APPROXIMATE_NOT_APPROVED` or `UNAVAILABLE` "
        "family may be silently selected into the 2026 production feature set -- see "
        "`nfl_hybrid.providers.balldontlie.parity.assert_production_eligible`.",
        "",
        "| Feature family | Parity status | Production eligible |",
        "|---|---|---|",
    ]
    for entry in PARITY_MATRIX:
        lines.append(
            f"| {entry.feature_family} | `{entry.parity_status}` | "
            f"{'YES' if entry.production_eligible else 'no'} |"
        )
    lines.append("")
    for entry in PARITY_MATRIX:
        lines.extend(
            [
                f"## {entry.feature_family}",
                "",
                f"- **Parity status:** `{entry.parity_status}` "
                f"({'production-eligible' if entry.production_eligible else 'NOT production-eligible'})",
                f"- **Historical source:** {entry.historical_source}",
                f"- **Historical definition:** {entry.historical_definition}",
                f"- **Live source:** {entry.live_source}",
                f"- **Live definition:** {entry.live_definition}",
                f"- **Validation evidence:** {entry.validation_evidence}",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> int:
    records = as_records()
    JSON_OUTPUT_PATH.write_text(json.dumps(records, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    MD_OUTPUT_PATH.write_text(_render_markdown(), encoding="utf-8")
    eligible = sum(1 for r in records if r["production_eligible"])
    print(
        f"Wrote {len(records)} parity entries to {JSON_OUTPUT_PATH} and {MD_OUTPUT_PATH} "
        f"({eligible} production-eligible)."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
